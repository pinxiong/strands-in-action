def module_path(import_name: str) -> Path:
    spec = importlib.util.find_spec(import_name)
    if spec is None or spec.origin is None:
        raise RuntimeError(f"cannot locate {import_name}")
    return Path(spec.origin)


def relpath(p: Path) -> str:
    # e.g. strands/multiagent/graph.py  or  strands_tools/workflow.py
    parts = p.parts
    for anchor in ("strands", "strands_tools"):
        if anchor in parts:
            i = parts.index(anchor)
            return "/".join(parts[i:])
    return p.name


def main() -> None:
    lines: list[str] = [
        "# Source blocks — UC10 (orchestrating-mixed)",
        "",
        f"Verified against installed packages: `{SA}`, `{SAT}`, Python 3.11.",
        "Every block is sliced verbatim from the interpreter's site-packages,",
        "then `textwrap.dedent()` removes the common leading indent so the first",
        "code line is flush-left. The `# path:lines` header is at column 0.",
        "Line numbers are 1-based, inclusive, from the installed source file.",
        "Generated by `src/gen_source_blocks.py` (re-runnable).",
        "",
    ]

    for title, import_name, version, spans in BLOCKS:
        path = module_path(import_name)
        src_lines = path.read_text().splitlines()
        lines.append(f"## {title}")
        lines.append("")
        lines.append(f"Source: `{relpath(path)}` — {version}")
        lines.append("")
        for start, end in spans:
            chunk = "\n".join(src_lines[start - 1 : end])
            chunk = textwrap.dedent(chunk)
            header = f"# {relpath(path)}:{start}-{end} -- verbatim, {version}"
            lines.append("```python")
            lines.append(header)
            lines.append(chunk.rstrip("\n"))
            lines.append("```")
            lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(BLOCKS)} sections, "
          f"{sum(len(s) for *_, s in BLOCKS)} blocks)")


if __name__ == "__main__":
    main()
